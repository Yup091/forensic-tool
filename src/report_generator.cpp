std::string ReportGenerator::generateHTMLFooter() {
    std::stringstream ss;
    ss << "    <div class=\"footer\">\n"
       << "        <p>Generated by Forensic Data Tool</p>\n"
       << "        <p>" << getCurrentTimestamp() << "</p>\n"
       << "    </div>\n"
       << "</body>\n"
       << "</html>\n";
    return ss.str();
}

std::string ReportGenerator::formatStatusHTML(const std::string& status) {
    if (status == "SUCCESS" || status == "PASSED") {
        return "<span class=\"status-pass\">" + status + "</span>";
    } else if (status == "FAILED") {
        return "<span class=\"status-fail\">" + status + "</span>";
    } else if (status == "INCONCLUSIVE") {
        return "<span class=\"status-inconclusive\">" + status + "</span>";
    }
    return status;
}

std::string ReportGenerator::generateTextReport(
    const AuditRecord& record,
    const std::string& outputPath) {
    
    // Create output directory
    try {
        fs::create_directories(outputPath);
    } catch (const std::exception& e) {
        std::cerr << "[ERROR] Failed to create directory: " << e.what() << std::endl;
        return "";
    }
    
    std::string fileName = outputPath + record.caseID + "_report.txt";
    std::ofstream file(fileName);
    
    if (!file.is_open()) {
        std::cerr << "[ERROR] Failed to open file for writing: " << fileName << std::endl;
        return "";
    }
    
    file << "╔════════════════════════════════════════════════════════════════╗\n";
    file << "║              FORENSIC OPERATION REPORT                         ║\n";
    file << "║                                                                ║\n";
    file << "╚════════════════════════════════════════════════════════════════╝\n\n";
    
    file << "REPORT METADATA\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << "Generated: " << getCurrentTimestamp() << "\n";
    file << "Case ID:   " << record.caseID << "\n";
    file << "Tool:      Forensic Data Tool v1.0\n\n";
    
    file << "OPERATION SUMMARY\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << "Operation Type:    " << record.operationType << "\n";
    file << "Status:            " << record.status << "\n";
    file << "Method:            " << record.method << "\n";
    file << "Exit Code:         " << record.exitCode << "\n\n";
    
    file << "DEVICE INFORMATION\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << "Device Path:       " << record.device << "\n";
    file << "Device Model:      " << record.deviceModel << "\n";
    file << "Device Serial:     " << record.deviceSerial << "\n";
    file << "Device Size:       " << record.deviceSize << "\n\n";
    
    file << "OPERATION TIMELINE\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << "Start Time:        " << record.startTime << "\n";
    file << "End Time:          " << record.endTime << "\n\n";
    
    if (record.operationType == "RECOVERY") {
        file << "RECOVERY RESULTS\n";
        file << "════════════════════════════════════════════════════════════════\n";
        file << "Files Recovered:   " << record.filesRecovered << "\n\n";
    } else if (record.operationType == "ERASURE") {
        file << "ERASURE RESULTS\n";
        file << "════════════════════════════════════════════════════════════════\n";
        file << "Erasure Method:    " << record.method << "\n";
        file << "Status:            " << (record.status == "SUCCESS" ? "COMPLETE" : "INCOMPLETE") << "\n\n";
    } else if (record.operationType == "VERIFICATION") {
        file << "VERIFICATION RESULTS\n";
        file << "════════════════════════════════════════════════════════════════\n";
        file << "Clearance:         " << std::fixed << std::setprecision(2) << record.erasurePercentage << "%\n";
        file << "Status:            " << record.status << "\n\n";
    }
    
    file << "OPERATION DETAILS\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << record.details << "\n\n";
    
    file << "INTEGRITY\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << "Record Hash:       " << record.sha256Hash << "\n\n";
    
    file << "CHAIN OF CUSTODY\n";
    file << "════════════════════════════════════════════════════════════════\n";
    file << "This report represents an official forensic record.\n";
    file << "Any tampering with this document constitutes legal violation.\n\n";
    
    file << "═════════════════════════════════════════════════════════════════\n";
    file << "END OF REPORT\n";
    
    file.close();
    
    std::cout << "[✓] Text report generated: " << fileName << "\n";
    return fileName;
}

