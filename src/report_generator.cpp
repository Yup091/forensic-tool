std::string ReportGenerator::generateAuditSummary(
    const std::vector<std::string>& caseIDs,
    const std::string& outputPath) {
    
    // Create output directory
    try {
        fs::create_directories(outputPath);
    } catch (const std::exception& e) {
        std::cerr << "[ERROR] Failed to create directory: " << e.what() << std::endl;
        return "";
    }
    
    std::string fileName = outputPath + "audit_summary.txt";
    std::ofstream file(fileName);
    
    if (!file.is_open()) {
        std::cerr << "[ERROR] Failed to open file for writing: " << fileName << std::endl;
        return "";
    }
    
    file << "╔════════════════════════════════════════════════════════════════╗\n";
    file << "║              FORENSIC AUDIT SUMMARY                            ║\n";
    file << "╚════════════════════════════════════════════════════════════════╝\n\n";
    
    file << "Generated: " << getCurrentTimestamp() << "\n";
    file << "Total Cases: " << caseIDs.size() << "\n\n";
    
    file << "CASE INDEX\n";
    file << "════════════════════════════════════════════════════════════════\n";
    
    for (size_t i = 0; i < caseIDs.size(); ++i) {
        file << (i + 1) << ". " << caseIDs[i] << "\n";
    }
    
    file << "\n════════════════════════════════════════════════════════════════\n";
    file << "END OF SUMMARY\n";
    
    file.close();
    
    std::cout << "[✓] Audit summary generated: " << fileName << "\n";
    return fileName;
}

